import mongoose from "mongoose";

const defaultMessageSchema = new mongoose.Schema(
  {
    title: {
      type: String,
      required: true,
      trim: true,
    },
    message: {
      type: String,
      required: true,
      trim: true,
    },
    userId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },
  },
  {
    timestamps: true, 
  }
);

const DefaultMessage = mongoose.model("DefaultMessage", defaultMessageSchema);

export default DefaultMessage;